    private static final class BatchImpl implements JdbcQueryBatch {
        private final String sourceSql;
        private final String sql;
        private final JdbcQueryOptions options;
        private final List<JdbcQuery> rows;

        private BatchImpl(String sourceSql, String sql, JdbcQueryOptions options, List<JdbcQuery> rows) {
            this.sourceSql = sourceSql;
            this.sql = sql;
            this.options = options;
            this.rows = Collections.unmodifiableList(rows);
        }

        @Override
        public String sourceSql() {
            return this.sourceSql;
        }

        @Override
        public String sql() {
            return this.sql;
        }

        @Override
        public JdbcQueryOptions options() {
            return this.options;
        }

        @Override
        public int size() {
            return this.rows.size();
        }

        @Override
        public List<Parameter> parameters(int index) {
            return this.rows.get(index).parameters();
        }

        @Override
        public PreparedStatement prepare(Connection connection) throws UncheckedSqlException {
            if (this.rows.isEmpty()) {
                throw new IllegalArgumentException("JDBC batch query cannot be prepared because batch is empty; handle empty input before calling the repository method");
            }

            PreparedStatement statement = null;
            try {
                statement = prepareStatement(connection, this.sql, this.options);
                for (int i = 0; i < this.rows.size(); i++) {
                    bindParameters(statement, this.rows.get(i).parameters());
                    statement.addBatch();
                }
                return statement;
            } catch (SQLException e) {
                closeOnError(statement, e);
                throw new UncheckedSqlException(e);
            }
        }
    }

    private static ParsedQuery parse(String sourceSql, Map<String, ParameterValue> params) {
        var sql = new StringBuilder(sourceSql.length());
        var parameters = new ArrayList<Parameter>();
        var usedParams = new HashSet<String>(params.size());
        boolean singleQuoted = false;
        boolean doubleQuoted = false;

        for (int i = 0; i < sourceSql.length(); i++) {
            char c = sourceSql.charAt(i);
            if (c == '\'' && !doubleQuoted) {
                singleQuoted = !singleQuoted;
                sql.append(c);
                continue;
            }
            if (c == '"' && !singleQuoted) {
                doubleQuoted = !doubleQuoted;
                sql.append(c);
                continue;
            }
            if (c != ':' || singleQuoted || doubleQuoted) {
                sql.append(c);
                continue;
            }
            if (i + 1 < sourceSql.length() && sourceSql.charAt(i + 1) == ':') {
                sql.append("::");
                i++;
                continue;
            }
            if (i > 0 && sourceSql.charAt(i - 1) == ':') {
                sql.append(c);
                continue;
            }

            int nameStart = i + 1;
            if (nameStart >= sourceSql.length() || !isNameStart(sourceSql.charAt(nameStart))) {
                sql.append(c);
                continue;
            }

            int nameEnd = nameStart + 1;
            while (nameEnd < sourceSql.length() && isNamePart(sourceSql.charAt(nameEnd))) {
                nameEnd++;
            }

            var name = sourceSql.substring(nameStart, nameEnd);
            if (!params.containsKey(name)) {
                throw new IllegalArgumentException("SQL query parameter ':%s' is not provided; fix the SQL placeholder or repository method parameter".formatted(name));
            }
            usedParams.add(name);
            appendParameter(sql, parameters, name, params.get(name));
            i = nameEnd - 1;
        }

        if (usedParams.size() != params.size()) {
            for (var param : params.keySet()) {
                if (!usedParams.contains(param)) {
                    throw new IllegalArgumentException("SQL query parameter ':%s' is provided but not used; add :%s to SQL or remove this parameter from the repository method/query builder".formatted(param, param));
                }
            }
        }

        return new ParsedQuery(sql.toString(), parameters);
    }

    private static void appendParameter(StringBuilder sql, List<Parameter> parameters, String name, ParameterValue value) {
        var values = value.values();
        if (!value.expandable()) {
            sql.append('?');
            var parameterValue = values.getFirst();
            parameters.add(new Parameter(name, parameterValue, value.binder(parameterValue)));
            return;
        }
        if (values.isEmpty()) {
            throw new IllegalArgumentException("SQL query parameter ':%s' collection is empty; empty collections cannot be expanded into SQL placeholders, handle empty input before calling the repository method".formatted(name));
        }

        int size = values.size();
        for (int i = 0; i < size; i++) {
            if (i > 0) {
                sql.append(", ");
            }
            sql.append('?');
        }

        for (int i = 0; i < size; i++) {
            var item = values.get(i);
            parameters.add(new Parameter(name, item, value.binder(item)));
        }
    }

    private static List<Object> values(Iterable<?> values) {
        var result = new ArrayList<>(4);
        for (var value : values) {
            result.add(value);
        }
        return result;
    }

    private static Parameter templateParameter(@Nullable Object value, BinderFactory binderFactory) {
        return new Parameter("", value, binderFactory.create(value));
    }

    private static boolean isNameStart(char c) {
        return Character.isLetter(c) || c == '_';
    }

    private static boolean isNamePart(char c) {
        return Character.isLetterOrDigit(c) || c == '_';
    }

    private record ParameterValue(List<?> values, boolean expandable, BinderFactory binderFactory) {
        JdbcParameterBinder binder(@Nullable Object value) {
            return this.binderFactory.create(value);
        }
    }

    private interface BinderFactory {
        JdbcParameterBinder create(@Nullable Object value);
    }

    private record ParsedQuery(String sql, List<Parameter> parameters) {}

    @Override
    public boolean equals(Object o) {
        if (!(o instanceof JdbcQuery jdbcQuery)) {
            return false;
        }
        return Objects.equals(this.sql, jdbcQuery.sql())
            && Objects.equals(this.parameters(), jdbcQuery.parameters())
            && Objects.equals(this.options, jdbcQuery.options());
    }

    @Override
    public int hashCode() {
        return Objects.hash(this.sql, this.parameters(), this.options);
    }

    @Override
    public String toString() {
        return this.sourceSql;
    }
